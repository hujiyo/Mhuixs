void print_logo(FILE *out)
{
    if (!out) return;

    srand((unsigned)time(NULL));

    /* 彩蛋概率 0.0314% */
    const char *art = ((rand() % 1000000) < 314) ? logo_hook : logo_mhuixs;

    const size_t len    = strlen(art);
    const int    lines  = (int)(len / LOGO_WIDTH);

    for (int i = 0; i < lines; i++) {
        for (int j = 0; j < LOGO_WIDTH; j++) {
            if (art[i * LOGO_WIDTH + j] == '1')
                fputc((rand() % 100 > 50) ? ('A' + rand() % 26) : ('a' + rand() % 26), out);
            else
                fputc(' ', out);
        }
        fputc('\n', out);
    }
    fputc('\n', out);

    for (size_t i = 0; i < sizeof(info_lines) / sizeof(info_lines[0]); i++)
        fprintf(out, "%s\n", info_lines[i]);
}
